use playz_core::contracts::*;
use ts_rs::{TS,Config};
fn main()->Result<(),Box<dyn std::error::Error>>{
    let config=Config::default();
    let declarations=[Phase::decl(&config),Settings::decl(&config),Choice::decl(&config),CaptureTarget::decl(&config),Encoder::decl(&config),Capabilities::decl(&config),Snapshot::decl(&config),Recording::decl(&config),LibraryPage::decl(&config),Details::decl(&config),Bookmark::decl(&config),ExportMode::decl(&config),ExportRequest::decl(&config),ExportJob::decl(&config),Diagnostic::decl(&config)];
    let content=format!("// Generated by cargo run -p playz-core --bin generate-contracts. Do not edit.\n{}\n",declarations.into_iter().map(|d|format!("export {d}")).collect::<Vec<_>>().join("\n"));
    let destination=std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../apps/desktop/src/contracts.ts");
    if std::env::args().any(|a|a=="--check") {if std::fs::read_to_string(&destination)?!=content{return Err("Generated Rust/TypeScript contracts have drifted".into());}}
    else {std::fs::create_dir_all(destination.parent().unwrap())?;std::fs::write(destination,content)?;}
    Ok(())
}
